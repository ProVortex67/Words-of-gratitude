-- Words of Gratitude: public community wall
-- Run this entire file in the Supabase SQL Editor.
-- Public entries are visible to anyone. Do not collect sensitive information.

create table if not exists public.gratitude_entries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 24),
  message text not null check (char_length(trim(message)) between 1 and 180),
  created_at timestamptz not null default now()
);

alter table public.gratitude_entries enable row level security;

create policy "Anyone can read gratitude entries"
on public.gratitude_entries
for select
to anon, authenticated
using (true);

create policy "Anyone can add a gratitude entry"
on public.gratitude_entries
for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 1 and 24
  and char_length(trim(message)) between 1 and 180
);

-- No public update or delete policy is intentionally provided.

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'gratitude_entries'
  ) then
    alter publication supabase_realtime add table public.gratitude_entries;
  end if;
end $$;

create index if not exists gratitude_entries_created_at_idx
on public.gratitude_entries (created_at desc);
